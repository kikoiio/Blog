import assert from 'node:assert/strict';
import { MagneticSand,sandAt } from '../src/interactions/magnetic-sand.js';
assert(sandAt({x:.75,y:.87}));assert(!sandAt({x:.4,y:.4}),'ocean cannot become magnetic sand');
const sand=new MagneticSand(500);sand.configure('04-black-beach.png');
assert.equal(sand.points.length,500);assert(sand.points.every(p=>sandAt(p)));
assert(!sand.down({x:.2,y:.3}));
sand.move({x:.75,y:.87});for(let i=0;i<40;i++)sand.advance(1/60);
assert(sand.measure().moved>10,'hover must visibly move a local cluster');
assert(sand.down({x:.75,y:.87}));for(let i=0;i<10;i++)sand.advance(1/60);assert(!sand.up(),'short presses stay playful');
sand.down({x:.75,y:.87});for(let i=0;i<60;i++)sand.advance(1/60);assert(!sand.up(true),'pointer cancellation must never navigate');
sand.down({x:.75,y:.87});for(let i=0;i<60;i++)sand.advance(1/60);assert(sand.up(),'deliberate hold/release opens existing articles');
sand.startOpening();for(let i=0;i<80;i++)sand.advance(1/60);assert.equal(sand.opening,1);
assert(sand.points.every(p=>Number.isFinite(p.x)&&Number.isFinite(p.y)));
sand.reset();assert.equal(sand.opening,0);assert.equal(sand.held,false);
sand.configure('13-hornbjarg.png');assert.equal(sand.points.length,0);assert.equal(sand.active,false);
console.log('PASS: sand geography, local movement, deliberate activation, cancel/no-navigation, finite convergence, scene reset.');
const {CityWindows}=await import('../src/interactions/city-windows.js');
const city=new CityWindows();city.configure('02-city-clear.png',{width:1672,height:941});
assert(city.active);for(const p of city.keyPoints)assert(city.hit(p)>=0,p.id+' broad facade hit');
assert.equal(city.hit({x:.5,y:.1}),-1,'sky is not a portal');assert.equal(city.hit({x:.5,y:.85}),-1,'road is not a portal');
city.move(city.keyPoint);for(let i=0;i<30;i++)city.advance(1/60);
assert(city.values.some(v=>v>.6),'a broad facade brings up the window response');
city.down(city.keyPoint);city.move({x:.5,y:.1});city.move(city.keyPoint);assert(!city.up(),'dragging off and returning must cancel');
city.down(city.keyPoint);assert(!city.up(true),'cancelled facade press cannot navigate');
city.move(city.keyPoint);city.startOpening();let events=0;for(let i=0;i<100;i++)if(city.advance(1/60))events++;
assert.equal(events,1,'keyboard entry completion fires exactly once');
city.reset();city.startOpening();assert(city.advance(.01,true),'reduced motion opens immediately');assert(!city.advance(.01,true));
city.configure('04-black-beach.png',{width:1672,height:941});assert(!city.active);assert.equal(city.hit(city.keyPoint),-1);
console.log('PASS: facade hit regions, calm window response, drag/cancel, keyboard entry, one-shot completion and city-only activation.');
const lowFrames=new MagneticSand(50);lowFrames.configure('04-black-beach.png');lowFrames.down({x:.75,y:.87});
assert(lowFrames.up(false,900),'real input duration must activate even if render frames were skipped');
lowFrames.reset();lowFrames.down({x:.75,y:.87});assert(!lowFrames.up(true,900),'cancel beats elapsed hold time');
console.log('PASS: hold duration independent of simulation frames; cancellation wins.');
